def phrase(pool: List[str], **kwargs) -> str:
    text = random.choice(pool)
    return text.format(**kwargs) if kwargs else text


def debt_phrase(total: float) -> str:
    if total == 0:
        return phrase(PHRASES_DEBT_ZERO)
    elif total > 500_000:
        return phrase(PHRASES_DEBT_HIGH)
    elif total > 100_000:
        return phrase(PHRASES_DEBT_MEDIUM)
    else:
        return phrase(PHRASES_DEBT_LOW)


def wednesday_phrase() -> str:
    return phrase(PHRASES_WEDNESDAY)


def maybe_lore() -> Optional[str]:
    """Лор с вероятностью 5%, пасхалка с вероятностью 2%."""
    roll = random.random()
    if roll < 0.02:
        return phrase(EASTER_EGGS)
    elif roll < 0.05:
        return phrase(LORE_PHRASES)
    return None


def format_amount(amount: float) -> str:
    return f"{amount:,.0f}".replace(",", " ")


